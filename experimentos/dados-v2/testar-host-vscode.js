"use strict";
const v=require('vscode'),assert=require('assert'),fs=require('fs'),path=require('path');
const pause=ms=>new Promise(r=>setTimeout(r,ms));
exports.run=async()=>{
  const root=v.workspace.workspaceFolders[0].uri.fsPath;
  assert(path.basename(root).startsWith('santafe-dados2-host-'));
  await v.commands.executeCommand('workbench.action.closeAuxiliaryBar');
  const file=path.join(root,'visual.fé'),source=fs.readFileSync(file,'utf8');
  let doc=await v.workspace.openTextDocument(file);
  doc=await v.languages.setTextDocumentLanguage(doc,'santafe-dados');
  const replace=async(document,text)=>{
    const edit=new v.WorkspaceEdit();
    edit.replace(document.uri,new v.Range(document.positionAt(0),document.positionAt(document.getText().length)),text);
    assert(await v.workspace.applyEdit(edit));assert.equal(document.getText(),text);
  };
  if(doc.getText()!==source) await replace(doc,source);
  await v.window.showTextDocument(doc,{preview:false});
  const ext=v.extensions.getExtension('santafe.santafe-dados-experimental'),api=await ext.activate();
  for(let i=0;i<150&&!api.estadoSLS().pronto;i++) await pause(100);
  assert(api.estadoSLS().pronto,JSON.stringify(api.estadoSLS()));
  assert.equal(api.estadoSLS().informação.version,'1.0.0-dados.2');
  const p=(s,last=false,delta=0)=>doc.positionAt((last?source.lastIndexOf(s):source.indexOf(s))+delta);
  const def=await v.commands.executeCommand('vscode.executeDefinitionProvider',doc.uri,p('saudação',true));
  assert.equal(def.length,1); assert.equal(def[0].range.start.line,1);
  const rename=await v.commands.executeCommand('vscode.executeDocumentRenameProvider',doc.uri,p('variável'),'posição');
  const edits=rename.get(doc.uri); assert(edits.length>=6); assert(edits.every(e=>doc.getText(e.range)==='variável'));
  assert(edits.every(e=>e.range.start.line!==9),'rename alterou colar bruto');
  const symbols=await v.commands.executeCommand('vscode.executeDocumentSymbolProvider',doc.uri);
  assert(symbols.some(s=>s.name==='lista'));
  const legend=await v.commands.executeCommand('vscode.provideDocumentSemanticTokensLegend',doc.uri);
  const sem=await v.commands.executeCommand('vscode.provideDocumentSemanticTokens',doc.uri);
  const tokens=[]; let line=0,char=0;
  for(let i=0;i<sem.data.length;i+=5){const [dl,dc,len,type]=sem.data.slice(i,i+4);line+=dl;char=dl?dc:char+dc;tokens.push({line,char,len,type:legend.tokenTypes[type]});}
  const at=s=>{const pos=p(s);return tokens.find(t=>t.line===pos.line&&t.char<=pos.character&&pos.character<t.char+t.len)?.type;};
  assert.equal(at('prefixo-'),'santafeEmbeddedString');
  assert.equal(at('-final'),'santafeEmbeddedString');
  assert.equal(at('retomado'),'santafeEmbeddedComment');
  assert.equal(at('const'),'santafeEmbeddedStorage');
  assert(!at('®variável permanece'));
  const change=new v.WorkspaceEdit(); change.insert(doc.uri,doc.positionAt(source.length),'\nlocal =\n');
  await v.workspace.applyEdit(change);
  for(let i=0;i<80&&!v.languages.getDiagnostics(doc.uri).length;i++) await pause(100);
  assert(v.languages.getDiagnostics(doc.uri).some(d=>d.severity===v.DiagnosticSeverity.Error));
  await replace(doc,source);
  await pause(500);
  for(let i=0;i<80&&v.languages.getDiagnostics(doc.uri).length;i++) await pause(100);
  assert.equal(v.languages.getDiagnostics(doc.uri).length,0);
  let data=await v.workspace.openTextDocument(path.join(root,'exemplo.onfé'));
  data=await v.languages.setTextDocumentLanguage(data,'onfe-experimental');
  const dataSource=fs.readFileSync(path.join(root,'exemplo.onfé'),'utf8');
  await v.window.showTextDocument(data,{preview:false});
  if(data.getText()!==dataSource) await replace(data,dataSource);
  await pause(500);
  for(let i=0;i<80&&v.languages.getDiagnostics(data.uri).length;i++) await pause(100);
  assert.equal(v.languages.getDiagnostics(data.uri).length,0);
  const invalid=new v.WorkspaceEdit();invalid.insert(data.uri,data.positionAt(data.getText().length),'\nimporte "nao-execute"');
  await v.workspace.applyEdit(invalid);
  for(let i=0;i<80&&!v.languages.getDiagnostics(data.uri).length;i++) await pause(100);
  assert(v.languages.getDiagnostics(data.uri).some(d=>d.severity===v.DiagnosticSeverity.Error));
  await replace(data,dataSource);
  await pause(500);
  for(let i=0;i<80&&v.languages.getDiagnostics(data.uri).length;i++) await pause(100);
  assert.equal(v.languages.getDiagnostics(data.uri).length,0);
  assert.equal(data.getText(),dataSource);
  await v.window.showTextDocument(await v.workspace.openTextDocument(file),{preview:false,preserveFocus:false,viewColumn:v.ViewColumn.One});
  const output={instante:new Date().toISOString(),editor:v.version,extensão:ext.packageJSON.version,sls:api.estadoSLS().informação,
    definição:true,rename:true,símbolos:true,incremental:true,onfe:true,tokens,resultado:'ok'};
  fs.writeFileSync(path.join(root,'vscode-resultado.json'),JSON.stringify(output,null,2));
  console.log('VSCODE_DADOS2_HOST_OK');
  if(process.env.SANTAFE_DADOS_VISUAL==='1') await pause(45000);
};
