#!/usr/bin/env python3
"""Gera tabelas GCB/EP/InCB e identificadores, offline, do Unicode 17.0.0."""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'ferramentas/unicode/17.0.0'

def ranges(name, select):
    result = []
    for line in (DATA / name).read_text(encoding='utf-8').splitlines():
        fields = [p.strip() for p in line.split('#')[0].split(';')]
        if len(fields) < 2:
            continue
        prop = select(fields)
        if prop is None:
            continue
        bounds = fields[0].split('..')
        result.append((int(bounds[0], 16), int(bounds[-1], 16), prop))
    result.sort()
    merged = []
    for a, b, p in result:
        if merged and merged[-1][1] + 1 == a and merged[-1][2] == p:
            merged[-1] = (merged[-1][0], b, p)
        else:
            merged.append((a, b, p))
    return merged

def generate():
    gcb = {'CR': 'CR', 'LF': 'LF', 'Control': 'CONTROL', 'Extend': 'EXTEND',
           'ZWJ': 'ZWJ', 'Regional_Indicator': 'RI', 'Prepend': 'PREPEND',
           'SpacingMark': 'SPACINGMARK', 'L': 'L', 'V': 'V', 'T': 'T'}
    tables = [
        ('gcb', ranges('GraphemeBreakProperty.txt', lambda f: 'GCB_' + gcb[f[1]] if f[1] in gcb else None)),
        ('ep', ranges('emoji-data.txt', lambda f: '1' if f[1] == 'Extended_Pictographic' else None)),
        ('incb', ranges('DerivedCoreProperties.txt', lambda f: 'INCB_' + f[2].upper() if f[1] == 'InCB' else None)),
        ('identifier', ranges('DerivedGeneralCategory.txt', lambda f:
            '1' if f[1].startswith('L') else '2' if f[1][0] in 'MN' else None)),
    ]
    output = ['/* Generated by ferramentas/gerar_unicode.py; Unicode 17.0.0.',
              ' * Official UCD data and license: ferramentas/unicode/17.0.0.',
              ' * Do not edit by hand. */',
              'typedef struct { unsigned int first, last; int property; } luaU_Range;']
    for name, values in tables:
        output.append('static const luaU_Range luaU_' + name + '_ranges[] = {')
        output.extend('  {0x%X, 0x%X, %s},' % row for row in values)
        output.append('};')
    return '\n'.join(output) + '\n'

if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'src/lunicode-ranges.h'
    if args.check:
        assert target.read_text() == generate(), 'tabelas Unicode desatualizadas'
    else:
        target.write_text(generate(), encoding='utf-8')
    for p in sorted(DATA.glob('*.txt')):
        print(hashlib.sha256(p.read_bytes()).hexdigest(), p.name)
